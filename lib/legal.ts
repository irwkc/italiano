const statusLabel: Record<OperatorStatus, string> = {
  individual: "физическое лицо",
  self_employed: "плательщик налога на профессиональный доход (самозанятый)",
  ip: "индивидуальный предприниматель",
};

function nonEmpty(...parts: string[]) {
  return parts.map((p) => p.trim()).filter(Boolean);
}

/** Строка для документов: статус + только заполненные реквизиты. */
export function operatorIdentity(): string {
  const bits = [`${operator.name} (${operator.nameEn})`, statusLabel[operator.status]];
  if (operator.inn) bits.push(`ИНН ${operator.inn}`);
  if (operator.status === "ip" && operator.ogrnip) bits.push(`ОГРНИП ${operator.ogrnip}`);
  if (operator.address) bits.push(operator.address);
  if (operator.email) bits.push(operator.email);
  if (operator.phone) bits.push(operator.phone);
  return bits.join(", ");
}

export function operatorContact(): string {
  const links = nonEmpty(operator.telegram, operator.email);
  return links.length ? links.join(", ") : operator.telegram;
}

